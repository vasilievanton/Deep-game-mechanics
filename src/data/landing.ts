export type CaseCategoryId = (typeof caseCategories)[number]['id'];

/**
 * Визуальная тема кейса: у каждого клиента свой фирменный стиль (src/styles/brands.css,
 * `[data-brand='…']`).
 */
export type CaseTheme =
  'mts' | 'mts-light' | 'tbank' | 'megafon' | 'zewa' | 'hh';

/**
 * Кейс собран как короткая история: задача → что собрали → итог. Правила наполнения:
 *  - в `outcome` поле `value` (цифра) заполняем только подтверждёнными числами; если цифр нет,
 *    пишем словами, что получилось (без `value`) — выдуманных результатов быть не должно;
 *  - в `facts` — только проверяемые факты (аудитория, срок, формат), без общих слов вроде «срок кампании».
 * Источники фактов указаны рядом с каждым кейсом.
 */
export type CaseItem = {
  id: string;
  /** Как клиент называется сейчас. */
  brand: string;
  /** Прежнее название, если клиент переименован («ex-Тинькофф»): показываем рядом, чтобы его узнавали. */
  brandNote?: string;
  title: string;
  /** Одной фразой: что это за проект. */
  description: string;
  categoryId: CaseCategoryId;
  /** Задача клиента. */
  task: string;
  /** Что собрали: 3–4 пункта. */
  built: readonly string[];
  /** Итог: цифры (`value`) только подтверждённые, иначе — что получилось словами. */
  outcome: readonly { value?: string; text: string }[];
  /** Проверяемые факты о проекте: аудитория, срок, формат. Может быть пусто. */
  facts: readonly { label: string; value: string }[];
  /** Теги механик (карточки на странице «Все кейсы»). */
  mechanics: readonly string[];
  artwork: 'mts' | 'club' | 'event' | 'promo' | 'referral';
  theme: CaseTheme;
  cover: string;
};

/** Бренд для текста и подписей: «Т-Банк (ex-Тинькофф)». */
export function caseBrand(item: Pick<CaseItem, 'brand' | 'brandNote'>) {
  return item.brandNote ? `${item.brand} (${item.brandNote})` : item.brand;
}

/** Ссылка на кейс в разделе «Кейсы» главной страницы: `/#case-<id>`. */
export function caseHref(id: string) {
  return `/#case-${id}`;
}

