export function featuredCaseForCategory(categoryId: CaseCategoryId) {
  return cases.find((item) => item.categoryId === categoryId) ?? cases[0];
}

export function categoryById(categoryId: CaseCategoryId) {
  return (
    caseCategories.find((item) => item.id === categoryId) ?? caseCategories[0]
  );
}

export function navHref(href: string, pathname: string) {
  if (href.startsWith('#') && pathname !== '/') {
    return `/${href}`;
  }
  return href;
}

